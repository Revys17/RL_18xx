"""Write an 1822-family variant's Rust data module from the Ruby engine's own
constants (dumped by scripts/g1822_title_data.rb in the ruby:3.2-slim rig).

    docker run --rm -v $PWD/logs/ruby/gems:/usr/local/bundle -v $PWD/logs/ruby/18xx:/18xx:ro \\
        -v $PWD/scripts:/probe:ro -v $PWD/logs/titledata:/out ruby:3.2-slim \\
        ruby /probe/g1822_title_data.rb G1822PNW /out/pnw.json
    python scripts/g1822_title_data.py logs/titledata/pnw.json engine-rs/src/title/g1822pnw_data.rs

The generated module holds data only (companies, corporations, trains,
phases, market, tiles, map, cert limits, starting cash, exchange tokens,
destinations); the hand-written title module next to it holds the
`GameTitle` impl and the family table. Nothing here is edited by hand.
"""

from __future__ import annotations

import json
import sys


def rs(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main(src: str, dst: str) -> None:
    d = json.load(open(src))
    c = d["consts"]
    out: list[str] = []
    w = out.append
    w(f"//! GENERATED by scripts/g1822_title_data.py from the Ruby engine's {d['title']}")
    w("//! constants (tobymao/18xx; scripts/g1822_title_data.rb dumps them). Do not")
    w("//! edit: regenerate. Data only — the title module next to this one holds the")
    w("//! `GameTitle` impl and the family table.")
    w("")
    w("#![allow(clippy::all)]")
    w("")
    w("use crate::title::{Capitalization, CompanyDef, CorpType, CorporationDef, PhaseDef, TrainDef};")
    w("")
    w(f"pub const TITLE: &str = {rs(d['title'])};")
    lo, hi = d["player_range"]
    w(f"pub const MIN_PLAYERS: u8 = {lo};")
    w(f"pub const MAX_PLAYERS: u8 = {hi};")
    w(f"pub const BANK_CASH: i32 = {c['BANK_CASH']};")
    w(f"pub const LAYOUT: &str = {rs(d['layout'])};")
    w("")
    for name, key in (("cert_limit", "CERT_LIMIT"), ("starting_cash", "STARTING_CASH")):
        ty = "u8" if name == "cert_limit" else "i32"
        w(f"/// {key}")
        w(f"pub fn {name}(num_players: u8) -> {ty} {{")
        w("    match num_players {")
        for k, v in sorted(c[key].items(), key=lambda kv: int(kv[0])):
            w(f"        {k} => {v},")
        w(f'        _ => panic!("{d["title"]}: invalid player count {{num_players}}"),')
        w("    }")
        w("}")
        w("")
    w("/// BIDDING_TOKENS (keyed by player count)")
    w("pub fn bidding_tokens(players: usize) -> i32 {")
    w("    match players {")
    for k, v in sorted(c["BIDDING_TOKENS"].items(), key=lambda kv: int(kv[0])):
        w(f"        {k} => {v},")
    w("        _ => 0,")
    w("    }")
    w("}")
    w("")
    w("pub const OPTIONAL_RULES: &[&str] = &[" + ", ".join(rs(o["sym"]) for o in d["optional_rules"]) + "];")
    for key in ("STARTING_COMPANIES", "STARTING_CORPORATIONS"):
        w(f"pub const {key}: &[&str] = &[" + ", ".join(rs(x) for x in c[key]) + "];")
    w("")

    # -- companies ------------------------------------------------------
    w("pub fn companies() -> Vec<CompanyDef> {")
    w("    let co = |sym: &'static str, name: &'static str, value: i32, revenue: i32| CompanyDef {")
    w("        sym,")
    w("        name,")
    w("        value,")
    w("        revenue,")
    w("        abilities: &[],")
    w("        discount: 0,")
    w("        auctionable: true,")
    w("    };")
    w("    vec![")
    for co in d["companies"]:
        line = f"co({rs(co['sym'])}, {rs(co['name'])}, {co['value']}, {co['revenue']})"
        if co.get("discount"):
            # Company#min_bid = value - discount (1822MX's C1: a $200 minimum)
            line = f"CompanyDef {{ discount: {co['discount']}, ..{line} }}"
        w(f"        {line},")
    w("    ]")
    w("}")
    w("")

    # -- corporations ---------------------------------------------------
    w("pub fn corporations() -> Vec<CorporationDef> {")
    w("    vec![")
    for cp in d["corporations"]:
        minor = cp.get("type") == "minor"
        shares = cp.get("shares") or [20, 10, 10, 10, 10, 10, 10, 10, 10]
        city = cp.get("city")
        w("        CorporationDef {")
        w(f"            sym: {rs(cp['sym'])},")
        w(f"            name: {rs(cp['name'])},")
        w(f"            token_prices: &{json.dumps(cp.get('tokens') or [])},")
        w(f"            home_hex: {rs(cp.get('coordinates') or '')},")
        w(f"            home_city_index: {city if city is not None else 'u8::MAX'},")
        w("            reserved: true,")
        w(f"            shares: &{json.dumps(shares)},")
        w(f"            float_percent: {cp.get('float_percent', 60)},")
        w("            capitalization: Capitalization::Incremental,")
        w(f"            corp_type: CorpType::{'Minor' if minor else 'Major'},")
        w(f"            max_ownership_percent: {cp.get('max_ownership_percent', 60)},")
        w(f"            always_market_price: {'true' if cp.get('always_market_price') else 'false'},")
        w("        },")
    w("    ]")
    w("}")
    w("")
    w("/// Major destinations (entities.rb `destination_coordinates`).")
    w("pub fn destination(sym: &str) -> Option<&'static str> {")
    w("    Some(match sym {")
    for cp in d["corporations"]:
        if cp.get("destination_coordinates"):
            w(f"        {rs(cp['sym'])} => {rs(cp['destination_coordinates'])},")
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    w("/// EXCHANGE_TOKENS.")
    w("pub fn exchange_tokens(sym: &str) -> u32 {")
    w("    match sym {")
    for k, v in c["EXCHANGE_TOKENS"].items():
        w(f"        {rs(k)} => {v},")
    w("        _ => 0,")
    w("    }")
    w("}")
    w("")

    # -- trains -----------------------------------------------------------
    # TrainDef.distance is the CITY count (an L's 1-city+1-town bucket is 1,
    # a P+'s 99/99 is 99), as title::g1822 keeps it.
    def dist(t):
        if isinstance(t, list):
            return max(int(x["pay"]) for x in t if "city" in x["nodes"])
        return int(t)

    w("pub fn trains() -> Vec<TrainDef> {")
    w("    let t = |name, distance, price, count, rusts_on, events: &'static [&'static str]| TrainDef {")
    w("        name,")
    w("        distance,")
    w("        price,")
    w("        count,")
    w("        rusts_on,")
    w("        multiplier: 1,")
    w("        obsolete_on: None,")
    w("        events,")
    w("        available_on: None,")
    w("        discount: &[],")
    w("    };")
    w("    vec![")
    variants = []
    for tr in d["trains"]:
        num = "u32::MAX" if tr["num"] == "unlimited" else tr["num"]
        rusts = f"Some({rs(tr['rusts_on'])})" if tr.get("rusts_on") else "None"
        ev = "&[" + ", ".join(rs(e["type"]) for e in tr.get("events") or []) + "]"
        w(f"        t({rs(tr['name'])}, {dist(tr['distance'])}, {tr['price']}, {num}, {rusts}, {ev}),")
        for v in tr.get("variants") or []:
            variants.append((tr["name"], v))
    w("        // -- variants (no physical cards of their own) --")
    for base, v in variants:
        rusts = f"Some({rs(v['rusts_on'])})" if v.get("rusts_on") else "None"
        extra = []
        if v.get("available_on"):
            extra.append(f"available_on: Some({rs(v['available_on'])})")
        if v.get("multiplier"):
            extra.append(f"multiplier: {v['multiplier']}")
        w(
            f"        TrainDef {{ {', '.join(extra + [''])}..t({rs(v['name'])}, {dist(v['distance'])}, "
            f"{v['price']}, 0, {rusts}, &[]) }},"
        )
    w("    ]")
    w("}")
    w("")
    w("/// The variant a train card may be bought as: (variant name, distance,")
    w("/// price, rusts_on).")
    w("pub fn train_variant(base: &str, variant: &str) -> Option<(&'static str, u32, i32, Option<&'static str>)> {")
    w("    match (base, variant) {")
    for tr in d["trains"]:
        if not tr.get("variants"):
            continue
        rusts = f"Some({rs(tr['rusts_on'])})" if tr.get("rusts_on") else "None"
        w(f"        ({rs(tr['name'])}, {rs(tr['name'])}) => Some(({rs(tr['name'])}, {dist(tr['distance'])}, {tr['price']}, {rusts})),")
        for v in tr["variants"]:
            vr = f"Some({rs(v['rusts_on'])})" if v.get("rusts_on") else "None"
            w(f"        ({rs(tr['name'])}, {rs(v['name'])}) => Some(({rs(v['name'])}, {dist(v['distance'])}, {v['price']}, {vr})),")
    w("        _ => None,")
    w("    }")
    w("}")
    w("")
    w("/// The variants of a base train card (Ruby `train.variants`), base first.")
    w("pub fn train_variants(base: &str) -> &'static [&'static str] {")
    w("    match base {")
    for tr in d["trains"]:
        if tr.get("variants"):
            names = [tr["name"]] + [v["name"] for v in tr["variants"]]
            w(f"        {rs(tr['name'])} => &[{', '.join(rs(n) for n in names)}],")
    w("        _ => &[],")
    w("    }")
    w("}")
    w("")

    # -- phases -----------------------------------------------------------
    w("pub fn phases() -> Vec<PhaseDef> {")
    w("    vec![")
    for ph in d["phases"]:
        on = ph.get("on")
        if isinstance(on, list):
            on = on[0]
        on = f"Some({rs(on)})" if on else "None"
        tl = ph["train_limit"]
        w("        PhaseDef {")
        w(f"            name: {rs(ph['name'])},")
        w(f"            on: {on},")
        w(f"            train_limit: {tl['major']},")
        w(f"            minor_train_limit: Some({tl['minor']}),")
        w(f"            tiles: &[{', '.join(rs(x) for x in ph['tiles'])}],")
        w(f"            operating_rounds: {ph['operating_rounds']},")
        w(f"            status: &[{', '.join(rs(x) for x in ph.get('status') or [])}],")
        w("        },")
    w("    ]")
    w("}")
    w("")

    # -- market -----------------------------------------------------------
    w("/// game.rb MARKET (cell codes verbatim).")
    w("pub const MARKET: &[&[&str]] = &[")
    for row in d["market"]:
        w("    &[" + ", ".join(rs(x) for x in row) + "],")
    w("];")
    w("")

    # -- tiles --------------------------------------------------------------
    w("/// map.rb TILES: (name, count, color, DSL, hidden); standard tiles' DSL")
    w("/// from Engine::Config::Tile. Count u32::MAX = unlimited.")
    w("pub const TILES: &[(&str, u32, &str, &str, bool)] = &[")
    for name, t in d["tiles"].items():
        cnt = "u32::MAX" if t["count"] == "unlimited" else t["count"]
        w(f"    ({rs(name)}, {cnt}, {rs(t['color'])}, {rs(t['code'])}, {'true' if t['hidden'] else 'false'}),")
    w("];")
    w("")

    # -- map --------------------------------------------------------------
    w("/// map.rb HEXES: (coord, DSL, color), in Ruby order.")
    w("pub const HEX_DSL: &[(&str, &str, &str)] = &[")
    for h in d["hexes"]:
        w(f"    ({rs(h['coord'])}, {rs(h['code'])}, {rs(h['color'])}),")
    w("];")
    w("")
    w("/// map.rb LOCATION_NAMES.")
    w("pub const LOCATION_NAMES: &[(&str, &str)] = &[")
    for k, v in d["location_names"].items():
        w(f"    ({rs(k)}, {rs(v)}),")
    w("];")
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(out)} lines")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
